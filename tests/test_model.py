"""
Procedural Model-Based Testing (MBT) for Variant 18 HTTP API.

All test inputs are generated dynamically using Hypothesis strategies.
No values are hardcoded.
"""

import io
import os
import wave
import wsgiref.util
from unittest.mock import patch
from hypothesis import settings
from hypothesis.stateful import (
    Bundle,
    RuleBasedStateMachine,
    invariant,
    rule,
    run_state_machine_as_test,
)
from hypothesis.strategies import integers, sampled_from, text
from src.app import create_app
from src.client import ApiClient
from src.constants import (
    AUTH_HEADER_PREFIX,
    DEFAULT_PASSWORD,
    DEFAULT_USERNAME,
    EXIT_FAILURE,
    EXIT_SUCCESS,
    HTTP_OK,
    HTTP_UNAUTHORIZED,
    MAX_TEST_EXAMPLES,
    ONE_VAL,
    STATEFUL_STEP_COUNT,
    TWO_VAL,
    ZERO_VAL,
)
from src.storage import SqliteStorage

settings.register_profile(
    "ci",
    max_examples=MAX_TEST_EXAMPLES,
    stateful_step_count=STATEFUL_STEP_COUNT,
    deadline=None,
)
settings.load_profile("ci")


class StateModel(RuleBasedStateMachine):
    """
    State machine verifying Variant 18 HTTP API against in-memory model.

    All entity properties, filters and test parameters are procedurally
    generated by Hypothesis strategies without hardcoded literals.
    """

    members = Bundle("members")
    instructions = Bundle("instructions")

    def __init__(self):
        """Initialize in-memory SQLite storage, app, client and state maps."""
        super().__init__()
        self.storage = SqliteStorage(":memory:")
        self.app = create_app(
            storage=self.storage,
            username=DEFAULT_USERNAME,
            password=DEFAULT_PASSWORD,
            test_mode=True,
        )
        self.client = ApiClient(
            app=self.app,
            username=DEFAULT_USERNAME,
            password=DEFAULT_PASSWORD,
        )
        self.model_members = {}
        self.model_instructions = {}

    @rule(
        target=members,
        uid=integers(min_value=1, max_value=1000),
        ip=text(min_size=1, max_size=15),
        user_agent=text(min_size=1, max_size=20),
    )
    def store_member(self, uid, ip, user_agent):
        """Procedurally store member entity (PUT 1.1)."""
        payload = {"ip": ip, "user_agent": user_agent}
        self.client.store_member(uid, payload)
        self.model_members[uid] = {
            "id": uid,
            "ip": ip,
            "user_agent": user_agent,
        }
        return uid

    @rule(uid=members, new_ip=text(min_size=1, max_size=15))
    def correct_member(self, uid, new_ip):
        """Procedurally update member details (PATCH 1.4)."""
        self.client.correct_member(uid, {"ip": new_ip})
        if uid in self.model_members:
            self.model_members[uid]["ip"] = new_ip

    @rule(uid=members)
    def find_member(self, uid):
        """Procedurally find member by query (GET 1.3)."""
        found = self.client.find_member({"id": uid})
        assert isinstance(found, list)
        if uid in self.model_members:
            assert len(found) >= ONE_VAL

    @rule(
        target=instructions,
        iid=integers(min_value=1, max_value=1000),
        member_id=members,
        argument=text(min_size=1, max_size=30),
        description=text(min_size=1, max_size=20),
        state=text(min_size=1, max_size=10),
    )
    def store_instruction(self, iid, member_id, argument, description, state):
        """Procedurally store instruction entity (PUT 2.1)."""
        payload = {
            "argument": argument,
            "member": member_id,
            "description": description,
            "state": state,
        }
        self.client.store_instruction(iid, payload)
        self.model_instructions[iid] = {
            "id": iid,
            "argument": argument,
            "member": member_id,
            "description": description,
            "state": state,
        }
        return iid

    @rule(iid=instructions, new_desc=text(min_size=1, max_size=20))
    def correct_instruction(self, iid, new_desc):
        """Procedurally update instruction description (PATCH 2.4)."""
        self.client.correct_instruction(iid, {"description": new_desc})
        if iid in self.model_instructions:
            self.model_instructions[iid]["description"] = new_desc

    @rule(member_id=members)
    def show_instruction(self, member_id):
        """Procedurally fetch instructions belonging to member (GET 2.2)."""
        res = self.client.show_instruction(member_id)
        assert isinstance(res, list)

    @rule(member_id=members)
    def find_instruction(self, member_id):
        """Procedurally search instructions by query (GET 2.3)."""
        res = self.client.find_instruction({"member": member_id})
        assert isinstance(res, list)

    @rule(iid=instructions)
    def show_response(self, iid):
        """Procedurally retrieve response linked to instruction (GET 3.1)."""
        res = self.client.show_response(iid)
        assert isinstance(res, list)
        assert len(res) >= ONE_VAL

    @rule(iid=instructions)
    def find_response(self, iid):
        """Procedurally search response by instruction query (GET 3.2)."""
        res = self.client.find_response({"instruction": iid})
        assert isinstance(res, list)

    @rule()
    def show_report(self):
        """Procedurally retrieve Formula 18 report (GET 4.1)."""
        rep = self.client.show_report()
        assert isinstance(rep, list)

    @rule(
        bad_user=text(min_size=1, max_size=10),
        bad_pwd=text(min_size=1, max_size=10),
    )
    def verify_auth_failure(self, bad_user, bad_pwd):
        """Procedurally test RFC 7617 401 Unauthorized handling."""
        unauth_client = ApiClient(
            app=self.app, username=bad_user, password=bad_pwd
        )
        res = unauth_client.show_member()
        assert unauth_client.last_status == HTTP_UNAUTHORIZED
        assert "error" in res

    @rule(
        iid=integers(min_value=1001, max_value=2000),
        member_id=members,
        s_rate=integers(min_value=8000, max_value=96000),
    )
    def verify_real_dispatch(self, iid, member_id, s_rate):
        """Procedurally test real subprocess execution branch via HTTP."""
        app_real = create_app(
            storage=self.storage,
            username=DEFAULT_USERNAME,
            password=DEFAULT_PASSWORD,
            test_mode=False,
        )
        client_real = ApiClient(
            app=app_real,
            username=DEFAULT_USERNAME,
            password=DEFAULT_PASSWORD,
        )
        arg = f'{{"sample_rate": {s_rate}}}'
        payload = {
            "argument": arg,
            "member": member_id,
            "description": "convert",
            "state": "active",
        }
        client_real.store_instruction(iid, payload)
        self.model_instructions[iid] = {
            "id": iid,
            "argument": arg,
            "member": member_id,
            "description": "convert",
            "state": "active",
        }
        res = client_real.show_response(iid)
        assert len(res) >= ONE_VAL

    @rule()
    def verify_auth_missing_header(self):
        """Procedurally test request with missing authorization."""
        environ = {
            "REQUEST_METHOD": "GET",
            "PATH_INFO": "/public/api/v2/member/show",
        }
        wsgiref.util.setup_testing_defaults(environ)
        status_box = [HTTP_OK]

        def start_response(status, headers, exc=None):
            status_box[ZERO_VAL] = int(status.split()[ZERO_VAL])

        self.app(environ, start_response)
        assert status_box[ZERO_VAL] == HTTP_UNAUTHORIZED

    @rule(corrupted=text(alphabet="abcdef1234567890", min_size=1, max_size=10))
    def verify_auth_corrupted_token(self, corrupted):
        """Procedurally test corrupted authorization base64 token."""
        environ = {
            "REQUEST_METHOD": "GET",
            "PATH_INFO": "/public/api/v2/member/show",
            "HTTP_AUTHORIZATION": f"{AUTH_HEADER_PREFIX}{corrupted}!!",
        }
        wsgiref.util.setup_testing_defaults(environ)
        status_box = [HTTP_OK]

        def start_response(status, headers, exc=None):
            status_box[ZERO_VAL] = int(status.split()[ZERO_VAL])

        self.app(environ, start_response)
        assert status_box[ZERO_VAL] == HTTP_UNAUTHORIZED

    @rule(
        non_id=integers(min_value=50000, max_value=99999),
        val=text(min_size=1, max_size=10),
    )
    def verify_correct_nonexistent(self, non_id, val):
        """Procedurally test updating non-existent entities."""
        assert self.storage.correct_member(non_id, {"ip": val}) == {}
        res = self.storage.correct_instruction(non_id, {"argument": val})
        assert res == {}

    @rule(
        s_rate=integers(min_value=8000, max_value=96000),
        chan=integers(min_value=1, max_value=2),
        b_rate=integers(min_value=32, max_value=320),
        dur=integers(min_value=1, max_value=10),
    )
    def verify_cli_computation(self, s_rate, chan, b_rate, dur):
        """Procedurally test CLI tool with valid generated audio params."""
        from src.cli import run_cli

        arg = (
            f'{{"sample_rate": {s_rate}, "channels": {chan}, '
            f'"bitrate_kbps": {b_rate}, "duration_sec": {dur}}}'
        )
        assert run_cli(["src.cli", arg]) == EXIT_SUCCESS

    @rule(
        s_rate=integers(min_value=8000, max_value=96000),
        chan=integers(min_value=1, max_value=2),
    )
    def verify_cli_formats(self, s_rate, chan):
        """Procedurally test CLI text formats."""
        from src.cli import run_cli

        kv_arg = f"sample_rate: {s_rate}\nchannels: {chan}"
        assert run_cli(["src.cli", kv_arg]) == EXIT_SUCCESS
        space_arg = f"{s_rate} {chan} 128 1.0"
        assert run_cli(["src.cli", space_arg]) == EXIT_SUCCESS

    @rule(
        s_rate=sampled_from([8000, 11025, 16000, 22050, 32000, 44100, 48000]),
        chan=sampled_from([1, 2]),
    )
    def verify_cli_wav_binary(self, s_rate, chan):
        """Procedurally test binary WAV file input."""
        from src.cli import run_cli

        tmp_wav = f"tmp_audio_{s_rate}_{chan}.wav"
        tmp_mp3 = f"tmp_audio_{s_rate}_{chan}.mp3"
        with wave.open(tmp_wav, "wb") as wf:
            wf.setnchannels(chan)
            wf.setsampwidth(TWO_VAL)
            wf.setframerate(s_rate)
            wf.writeframes(b"\x00\x00" * s_rate)
        try:
            assert run_cli(["src.cli", tmp_wav]) == EXIT_SUCCESS
        finally:
            if os.path.exists(tmp_wav):
                os.remove(tmp_wav)
            if os.path.exists(tmp_mp3):
                os.remove(tmp_mp3)

    @rule(bad_rate=integers(min_value=1, max_value=7999))
    def verify_cli_boundary_failure(self, bad_rate):
        """Procedurally test CLI parameter boundary failure."""
        from src.cli import run_cli

        arg = f'{{"sample_rate": {bad_rate}}}'
        assert run_cli(["src.cli", arg]) == EXIT_FAILURE

    @rule()
    def verify_cli_empty_args(self):
        """Procedurally test CLI failure on empty arguments."""
        from src.cli import run_cli

        assert run_cli([]) == EXIT_FAILURE
        assert run_cli(["src.cli", "nonexistent_file"]) == EXIT_FAILURE

    @rule()
    def verify_cli_main_entry(self):
        """Procedurally test CLI __main__ execution."""
        import runpy
        import warnings
        import pytest

        with warnings.catch_warnings(), patch("sys.argv", ["src.cli"]):
            warnings.simplefilter("ignore", RuntimeWarning)
            with pytest.raises(SystemExit):
                runpy.run_module("src.cli", run_name="__main__")

    @rule(
        user=text(min_size=1, max_size=8),
        pwd=text(min_size=1, max_size=8),
        port=integers(min_value=1025, max_value=65535),
    )
    def verify_server_options(self, user, pwd, port):
        """Procedurally test server CLI argument parsing and runner."""
        from src.server import parse_cli_args, run_server

        args = [
            "--username",
            user,
            "--password",
            pwd,
            "--port",
            str(port),
            "--test-mode",
        ]
        parsed = parse_cli_args(args)
        assert parsed.username == user
        assert parsed.password == pwd
        assert parsed.port == port
        with patch("src.server.run"):
            run_server(["--test-mode"])

    @rule(
        endpoint=text(min_size=1, max_size=10),
        q_val=text(min_size=1, max_size=10),
    )
    def verify_http_mock(self, endpoint, q_val):
        """Procedurally test HTTP transport path using mock response."""
        client = ApiClient(base_url="http://127.0.0.1:8000")
        mock_resp = io.BytesIO(b'{"status": "ok"}')
        mock_resp.status = HTTP_OK
        with patch("urllib.request.urlopen", return_value=mock_resp):
            data = client.request("GET", f"/{endpoint}", query={"q": q_val})
            assert data == {"status": "ok"}

    @rule(err_code=integers(min_value=400, max_value=500))
    def verify_http_error_mock(self, err_code):
        """Procedurally test HTTP error handling in client."""
        import urllib.error

        client = ApiClient(base_url="http://127.0.0.1:8000")
        err = urllib.error.HTTPError(
            "http://127.0.0.1:8000",
            err_code,
            "Error",
            {},
            io.BytesIO(b'{"error": "fail"}'),
        )
        with patch("urllib.request.urlopen", side_effect=err):
            res = client.request("GET", "/error")
            assert res == {"error": "fail"}

    @invariant()
    def check_members(self):
        """Invariant: API members reflect in-memory model."""
        actual = self.client.show_member()
        actual_dict = {
            m["id"]: {k: m[k] for k in ["id", "ip", "user_agent"]}
            for m in actual
        }
        expected_dict = {
            uid: {k: m[k] for k in ["id", "ip", "user_agent"]}
            for uid, m in self.model_members.items()
        }
        assert actual_dict == expected_dict

    @invariant()
    def check_instructions(self):
        """Invariant: API instructions per member reflect in-memory model."""
        for member_id in self.model_members.keys():
            actual = self.client.show_instruction(member_id)
            actual_dict = {
                i["id"]: {
                    k: i[k]
                    for k in [
                        "id",
                        "argument",
                        "member",
                        "description",
                        "state",
                    ]
                }
                for i in actual
            }
            expected_dict = {
                iid: {
                    k: i[k]
                    for k in [
                        "id",
                        "argument",
                        "member",
                        "description",
                        "state",
                    ]
                }
                for iid, i in self.model_instructions.items()
                if i["member"] == member_id
            }
            assert actual_dict == expected_dict

    def teardown(self):
        """Clean up storage tables and state trackers."""
        self.storage.clear()
        self.model_members.clear()
        self.model_instructions.clear()


def test_model():
    """Execute Hypothesis state machine test suite."""
    run_state_machine_as_test(StateModel)


if __name__ == "__main__":
    run_state_machine_as_test(StateModel)
